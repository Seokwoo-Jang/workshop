// 일정 지도 링크: 관리자 입력 '라벨 | URL' 줄 ↔ [{ label, url }] (검사는 서버 BAD_LINK)
export const parseLinks = s => s.split('\n').map(l => l.trim()).filter(Boolean).map(l => {
  const i = l.lastIndexOf('|');
  return i < 0 ? { label: '', url: l } : { label: l.slice(0, i).trim(), url: l.slice(i + 1).trim() };
});
export const fmtLinks = a => (a || []).map(l => `${l.label} | ${l.url}`).join('\n');
